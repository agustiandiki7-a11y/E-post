CREATE DATABASE IF NOT EXISTS `e-pos` CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE `e-pos`;
SET NAMES utf8mb4;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS `transaction_details`;
DROP TABLE IF EXISTS `transactions`;
DROP TABLE IF EXISTS `products`;
DROP TABLE IF EXISTS `users`;
DROP TABLE IF EXISTS `branches`;
SET FOREIGN_KEY_CHECKS = 1;

-- 1. branches
CREATE TABLE `branches` (
  `id`          INT NOT NULL AUTO_INCREMENT,
  `nama_cabang` VARCHAR(100) NOT NULL,
  `alamat`      TEXT,
  `telepon`     VARCHAR(20) DEFAULT NULL,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- 2. users
CREATE TABLE `users` (
  `id`        INT NOT NULL AUTO_INCREMENT,
  `nama`      VARCHAR(100) NOT NULL,
  `email`     VARCHAR(100) NOT NULL,
  `password`  VARCHAR(255) NOT NULL,
  `role`      ENUM('admin','kasir','manajer') NOT NULL,
  `branch_id` INT DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `email` (`email`),
  KEY `fk_users_branch` (`branch_id`),
  CONSTRAINT `fk_users_branch` FOREIGN KEY (`branch_id`) REFERENCES `branches` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- 3. products
CREATE TABLE `products` (
  `id`          INT NOT NULL AUTO_INCREMENT,
  `branch_id`   INT NOT NULL,
  `nama_produk` VARCHAR(150) NOT NULL,
  `harga_jual`  DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  `stok`        INT NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `fk_products_branch` (`branch_id`),
  CONSTRAINT `fk_products_branch` FOREIGN KEY (`branch_id`) REFERENCES `branches` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- 4. transactions  (status: selesai / menunggu_void / void)
CREATE TABLE `transactions` (
  `id`             INT NOT NULL AUTO_INCREMENT,
  `branch_id`      INT NOT NULL,
  `cashier_id`     INT NOT NULL,
  `invoice_number` VARCHAR(30) NOT NULL,
  `total_bayar`    DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  `diskon`         DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  `tanggal`        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `status`         ENUM('selesai','menunggu_void','void') NOT NULL DEFAULT 'selesai',
  PRIMARY KEY (`id`),
  UNIQUE KEY `invoice_number` (`invoice_number`),
  KEY `fk_trx_branch` (`branch_id`),
  KEY `fk_trx_cashier` (`cashier_id`),
  KEY `idx_trx_tanggal` (`tanggal`),
  CONSTRAINT `fk_trx_branch`  FOREIGN KEY (`branch_id`)  REFERENCES `branches` (`id`),
  CONSTRAINT `fk_trx_cashier` FOREIGN KEY (`cashier_id`) REFERENCES `users` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- 5. transaction_details
CREATE TABLE `transaction_details` (
  `id`             INT NOT NULL AUTO_INCREMENT,
  `transaction_id` INT NOT NULL,
  `product_id`     INT NOT NULL,
  `jumlah`         INT NOT NULL,
  `harga_satuan`   DECIMAL(15,2) NOT NULL,
  `subtotal`       DECIMAL(15,2) NOT NULL,
  PRIMARY KEY (`id`),
  KEY `fk_det_trx` (`transaction_id`),
  KEY `fk_det_product` (`product_id`),
  CONSTRAINT `fk_det_trx`     FOREIGN KEY (`transaction_id`) REFERENCES `transactions` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_det_product` FOREIGN KEY (`product_id`)     REFERENCES `products` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

